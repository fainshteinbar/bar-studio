// Builds the two files that get pasted into the Supabase SQL Editor:
//   invoices/supabase/install.sql         all migrations in order. Idempotent. Never removes anything.
//   invoices/supabase/dev/reset_test.sql  bfain-docs-test only: wipe, install, seed, re-mark.
// Usage: node scripts/build-install-sql.mjs   (npm run build:install-sql)
// The tests load the same migration files, so what is tested is what gets pasted.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const DIR = 'invoices/supabase';
const files = readdirSync(join(DIR, 'migrations')).filter((f) => /^\d{4}_.+\.sql$/.test(f)).sort();
const body = files.map((f) => `-- >>> ${f}\n${readFileSync(join(DIR, 'migrations', f), 'utf8').trim()}\n`).join('\n');

const install = `-- bfain.studio documents · install.sql
-- Generated by scripts/build-install-sql.mjs from invoices/supabase/migrations/. Do not edit by hand.
-- Paste into Supabase · SQL Editor · New query · Run. Then run seed/settings.sql once.
-- Safe to run again: it creates what is missing and never removes data.

${body}`;

if (/\bdrop\b/i.test(install)) {
  console.error('install.sql must never contain DROP. Check the migrations.');
  process.exit(1);
}
writeFileSync(join(DIR, 'install.sql'), install);

const seed = readFileSync(join(DIR, 'seed', 'settings.sql'), 'utf8').trim();
const reset = `-- ############################################################################
-- ##  FOR THE TEST PROJECT bfain-docs-test ONLY. NEVER RUN THIS IN bfain-docs.  ##
-- ############################################################################
-- Deletes every client, project, document, number counter and audit row, then installs again.
-- Generated by scripts/build-install-sql.mjs. Do not edit by hand.
--
-- Safety: it refuses to run unless the project carries the test marker that
-- dev/mark_test_project.sql creates. The production project never gets that marker.
-- Everything below runs as one statement batch: if the check fails, nothing happens.

do $$
begin
  if to_regclass('app.test_project_marker') is null then
    raise exception 'Refusing to reset: this is not the test project (no app.test_project_marker). Nothing was changed.';
  end if;
end $$;

drop function if exists public.issue_document(uuid) cascade;
drop function if exists public.issue_preview(uuid) cascade;
drop function if exists public.duplicate_document(uuid) cascade;
drop function if exists public.create_receipt_from_invoice(uuid, numeric, public.payment_method, date, text, text) cascade;
drop function if exists public.convert_quote_to_invoice(uuid) cascade;
drop function if exists public.mark_backup() cascade;
drop view if exists public.v_backup_status, public.v_received_yearly, public.v_received_monthly,
  public.v_client_open_balance, public.v_documents_recent, public.v_quote_status, public.v_invoice_balances cascade;
drop table if exists public.document_items, public.documents, public.projects, public.clients,
  public.settings, public.audit_log cascade;
drop type if exists public.payment_method, public.document_status, public.document_kind, public.currency cascade;
drop schema if exists app cascade;

${install}

-- >>> seed/settings.sql
${seed}

-- >>> test marker (keeps this project resettable)
create table if not exists app.test_project_marker (note text not null);
insert into app.test_project_marker (note) select 'bfain-docs-test'
 where not exists (select 1 from app.test_project_marker);
`;
writeFileSync(join(DIR, 'dev', 'reset_test.sql'), reset);

console.log(`install.sql: ${files.length} migrations (${files.join(', ')}); dev/reset_test.sql rebuilt`);
